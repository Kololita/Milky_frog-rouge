import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {ShiftTap,SHIFT_TAP_MS} from '../src/shift-tap.js';
import {movementInput} from '../src/movement.js';
const tap=new ShiftTap(),keys=new Set(['KeyW']);
assert.equal(tap.press('ShiftLeft',1000,keys),undefined,'Keydown must not request a dodge');
keys.add('ShiftLeft');assert(movementInput(keys).sprint,'Holding Shift+W must run immediately');
const quick=tap.release('ShiftLeft',1100,keys);assert(quick?.has('KeyW'));
assert.equal(tap.release('ShiftLeft',1101,keys),null,'A keyup cannot roll twice');
tap.press('ShiftLeft',2000,keys);tap.press('ShiftLeft',2100,keys);
assert.equal(tap.release('ShiftLeft',2000+SHIFT_TAP_MS+1,keys),null,'Repeat keydown must not restart the tap clock');
tap.press('ShiftRight',3000,keys);assert(tap.release('ShiftRight',3000+SHIFT_TAP_MS,keys));
tap.press('ShiftRight',4000,keys);assert.equal(tap.release('ShiftRight',5000,keys),null,'Running release must not roll');
tap.press('ShiftLeft',6000,keys);tap.reset();assert.equal(tap.release('ShiftLeft',6050,keys),null,'Blur/reset must cancel a pending tap');
tap.press('ShiftLeft',7000,keys);tap.press('ShiftRight',7040,keys);
assert.equal(tap.release('ShiftLeft',7090,keys),null);assert(tap.release('ShiftRight',7120,keys));
// Modifier chords can release WASD before Shift; retain the intended direction.
const diagonal=new Set(['KeyW','KeyD']);tap.press('ShiftLeft',8000,diagonal);
diagonal.clear();tap.rememberDirections(diagonal);
assert.deepEqual([...tap.release('ShiftLeft',8100,diagonal)].sort(),['KeyD','KeyW']);
tap.press('ShiftLeft',9000,new Set());assert.deepEqual([...tap.release('ShiftLeft',9080,new Set())],[]);
tap.press('ShiftLeft',10000,new Set(['KeyW']));tap.rememberDirections(new Set(['KeyA']));
assert.deepEqual([...tap.release('ShiftLeft',10100,new Set(['KeyA']))],['KeyA']);
tap.press('ShiftLeft',11000,new Set(['KeyW']));tap.rememberDirections(new Set(['KeyW','KeyS']));
assert.deepEqual([...tap.release('ShiftLeft',11090,new Set(['KeyW','KeyS']))],[]);
assert(movementInput(new Set(['KeyW','ShiftRight'])).sprint);
assert(!movementInput(new Set(['KeyW','KeyF'])).sprint);
assert(movementInput(new Set(['KeyS','ShiftLeft'])).sprint);
assert(movementInput(new Set(['KeyA','ShiftLeft'])).sprint);
const report={tapThresholdMs:SHIFT_TAP_MS,trigger:'Shift keyup',longHoldReleaseDoesNotDodge:true,sprint:'Shift+WASD',bothShiftKeys:true,blurCancelsPendingTap:true,chordDirectionPreserved:true};
await fs.writeFile(new URL('../output/animations/shift-tap-verification.json',import.meta.url),JSON.stringify(report,null,2));console.log('SHIFT_TAP_VERIFIED',report);
