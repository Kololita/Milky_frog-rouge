import assert from 'node:assert/strict';
import {gameFixture} from './game_fixture.mjs';
const g=await gameFixture(60),{read,mouse,tick,reset,hud}=g;g.freezeEnemy=true;
read('battle.enemy.z=30;battle.player.counterReady=true;battle.player.counterUntil=battle.time+3');mouse(1);tick(.55);
const partial=Number.parseFloat(hud.get('player-energy').style.values['--fill']);
assert(partial>0&&partial<33.34);assert.equal(read('battle.player.energy'),0);
tick(.2);assert(Number.parseFloat(hud.get('player-energy').style.values['--fill'])>partial);
tick(.6);assert.equal(read('battle.player.energy'),33);
reset();read('battle.emit("enemyHit",{damage:10,label:"test"})');tick(.02);
assert.equal(read('battleHUD.damageTotal'),10);assert.equal(hud.get('combo-damage').textContent,'10');
tick(1);read('battle.emit("enemyHit",{damage:12.5,label:"test"})');tick(.02);
assert.equal(read('battleHUD.damageTotal'),22.5);tick(2.9);assert.equal(read('battleHUD.damageTotal'),22.5);
tick(.12);assert.equal(read('battleHUD.damageTotal'),0);assert(hud.get('combo-damage').hidden);
read('battle.emit("enemyHit",{damage:8,label:"test"})');tick(.02);assert.equal(read('battleHUD.damageTotal'),8);
read('battle.emit("enemyHit",{damage:12.75,label:"test"});battle.player.health=85.9');tick(.02);
assert.equal(hud.get('combo-damage').textContent,'20');assert.equal(hud.get('health-value').textContent,'85 / 100');
g.tap('KeyQ');tick(.02);assert(read('lockArrow.visible'));assert.equal(read('lockArrow.position.x'),read('battle.enemy.x'));
read('battle.enemy.x+=.5');tick(.02);assert.equal(read('lockArrow.position.x'),read('battle.enemy.x'));
g.tap('KeyQ');tick(.02);assert(!read('lockArrow.visible'));
console.log('HUD_FEEDBACK_VERIFIED: progressive energy, actual completion, cumulative hits, three-second reset');
